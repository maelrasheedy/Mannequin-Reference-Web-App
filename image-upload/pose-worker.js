

// Task 1.2.6 - Run human pose detection in a Web Worker

// Receive an image from Sketch Upload
self.onmessage = async function (event) {

    const { runId, imageBitmap } = event.data;

    try {

        // Load the pose detection and calculation files
        const { detectHumanPose } = await import("./pose-detection.js");
        const { generateUserPoseJson } = await import("./pose-vector.js");

        // Make sure the worker received an image
        if (!imageBitmap) {
            throw new Error(
                "Pose detection failed: no image was received."
            );
        }

        // Detect the body landmarks in the worker
        const result = await detectHumanPose(imageBitmap);

        let userPoseJson = null;

        // Only calculate the pose if it passes 70% confidence
        if (
            result?.detected &&
            result.landmarks?.length &&
            Number.isFinite(result.averageLandmarkConfidence) &&
            result.averageLandmarkConfidence >= 0.7
        ) {

            // Check that MediaPipe returned the 3D world landmarks
            // needed to generate our 14-joint pose JSON.
            if (
                !Array.isArray(result.worldLandmarks) ||
                result.worldLandmarks.length < 33
            ) {
                throw new Error(
                    "Pose rejected: missing or incomplete 3D world landmarks."
                );
            }

            // Create our team's 14-joint pose data
            userPoseJson = generateUserPoseJson(
                result.worldLandmarks
            );

            // Do not send incomplete pose measurements to Search
            if (
                !userPoseJson ||
                !Array.isArray(userPoseJson.pose_vector) ||
                userPoseJson.pose_vector.length !== 14
            ) {
                throw new Error(
                    "Pose rejected: incomplete 14-joint pose JSON."
                );
            }

            // Keep the hidden-arm information generated by pose-vector.js
            // so the pose matcher can ignore estimated body segments.
            if (!Array.isArray(userPoseJson.estimated_segments)) {
                userPoseJson.estimated_segments = [];
            }

            console.log(
                "Web Worker generated 14-joint pose:",
                userPoseJson
            );
        }

        // Send the pose results back to Sketch Upload
        self.postMessage({
            type: "pose-result",
            runId,
            result,
            userPoseJson
        });

    } catch (error) {

        // Send an error message if processing fails
        self.postMessage({
            type: "pose-error",
            runId,
            message: error?.message || "Pose detection failed."
        });

    } finally {

        // Release the image after processing
        if (
            imageBitmap &&
            typeof imageBitmap.close === "function"
        ) {
            imageBitmap.close();
        }
    }
};
